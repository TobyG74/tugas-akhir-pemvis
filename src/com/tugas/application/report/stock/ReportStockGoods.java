    private void exportPDFButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_exportPDFButtonActionPerformed
        try {
            String namaFile = "src/com/tugas/application/report/file/stok_barang.jrxml";
            String namaFileCompile = "src/com/tugas/application/report/file/stok_barang.jasper";
            try (Connection conn = Connector.getConnection()) {
                HashMap parameter = new HashMap();
                JasperCompileManager.compileReportToFile(namaFile, namaFileCompile);
                JasperPrint jasperPrint = JasperFillManager.fillReport(namaFileCompile, parameter, conn);
                JasperViewer.viewReport(jasperPrint, false);
                JasperViewer.setDefaultLookAndFeelDecorated(true);
            } catch (Exception e) {
                Notifications.getInstance().show(Notifications.Type.ERROR, Notifications.Location.BOTTOM_RIGHT,
                    "Gagal saat membuat Report!");
                e.printStackTrace();
            }
        } catch (Exception e) {
            Notifications.getInstance().show(Notifications.Type.ERROR, Notifications.Location.BOTTOM_RIGHT,
                "Gagal saat Export Barang!");
            e.printStackTrace();
        }
    }//GEN-LAST:event_exportPDFButtonActionPerformed


