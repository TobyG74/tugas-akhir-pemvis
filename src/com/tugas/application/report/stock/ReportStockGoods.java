    public void loadDataTable() {
        tableModel = (DefaultTableModel) table.getModel();
        tableModel.setRowCount(0);

        String sql = "SELECT \n" +
            "b.id_barang,\n" +
            "b.nama_barang,\n" +
            "IFNULL(SUM(bm.jumlah), 0) AS total_masuk,\n" +
            "IFNULL(SUM(bk.jumlah), 0) AS total_keluar,\n" +
            "(IFNULL(SUM(bm.jumlah), 0) - IFNULL(SUM(bk.jumlah), 0)) AS stok_akhir\n" +
            "FROM barang AS b\n" +
            "LEFT JOIN barang_masuk AS bm ON b.id_barang = bm.id_barang\n" +
            "LEFT JOIN barang_keluar AS bk ON b.id_barang = bk.id_barang\n" +
            "GROUP BY b.id_barang, b.nama_barang\n" +
            "ORDER BY b.nama_barang;"; 
        try (Connection conn = Connector.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                Object[] row = new Object[]{
                    rs.getString("id_barang"),
                    rs.getString("nama_barang"),
                    rs.getString("total_masuk"), 
                    rs.getString("total_keluar"),
                    rs.getString("stok_akhir")
                };
                tableModel.addRow(row);
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }


