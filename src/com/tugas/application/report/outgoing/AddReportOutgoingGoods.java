    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
        if (inputIdBarangKeluar.getText().isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT,
                    "Tidak Dapat Menyimpan Data! Kamu Belum Mengisi ID Keluar!");
            return;
        }
        if (inputIdBarang.getText().isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT,
                    "Tidak Dapat Menyimpan Data! Kamu Belum Mengisi ID Barang!");
            return;
        }
        if (inputIdPelanggan.getText().isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT,
                    "Tidak Dapat Menyimpan Data! Kamu Belum Mengisi ID Pelanggan!");
            return;
        }
        if (inputJumlah.getText().isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT,
                    "Tidak Dapat Menyimpan Data! Kamu Belum Mengisi Jumlah!");
            return;
        }
        if (inputHargaKeluar.getText().isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT,
                    "Tidak Dapat Menyimpan Data! Kamu Belum Mengisi Harga Keluar!");
            return;
        }
        if (inputIdGudang.getText().isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.BOTTOM_RIGHT,
                    "Tidak Dapat Menyimpan Data! Kamu Belum Mengisi ID Gudang!");
            return;
        }

        String sqlCheck = "SELECT * FROM barang_keluar WHERE id_keluar = ?";
        String sqlInsert = "INSERT INTO barang_keluar (id_keluar, id_barang, id_pelanggan, jumlah, harga_keluar, id_gudang) VALUES (?, ?, ?, ?, ?, ?)";

        try (Connection conn = Connector.getConnection();
             PreparedStatement psCheck = conn.prepareStatement(sqlCheck)) {

            psCheck.setString(1, inputIdBarangKeluar.getText());
            ResultSet rs = psCheck.executeQuery();

            if (rs.next()) {
                Notifications.getInstance().show(Notifications.Type.INFO, Notifications.Location.BOTTOM_RIGHT,
                        "Data Barang Keluar dengan ID : " + inputIdBarangKeluar.getText().toUpperCase() + " sudah terdaftar!");
            } else {
                try (PreparedStatement psInsert = conn.prepareStatement(sqlInsert)) {
                    psInsert.setString(1, inputIdBarangKeluar.getText().toUpperCase());
                    psInsert.setString(2, inputIdBarang.getText());
                    psInsert.setString(3, inputIdPelanggan.getText());
                    psInsert.setInt(4, Integer.parseInt(inputJumlah.getText()));
                    psInsert.setBigDecimal(5, new java.math.BigDecimal(inputHargaKeluar.getText()));
                    psInsert.setString(6, inputIdGudang.getText());
                    psInsert.executeUpdate();
                    new ReportOutgoingGoods().loadDataTable();
                    Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.BOTTOM_RIGHT,
                        "Data Barang Dengan ID : " + inputIdBarang.getText().toUpperCase() + " Berhasil Di Simpan!");
                }
            }
        } catch (Exception e) {
            Notifications.getInstance().show(Notifications.Type.ERROR, Notifications.Location.BOTTOM_RIGHT,
                    "Terjadi Kesalahan Saat Menyimpan Data Barang Keluar");
            e.printStackTrace();
        }
        this.dispose();
    }//GEN-LAST:event_addBtnActionPerformed

